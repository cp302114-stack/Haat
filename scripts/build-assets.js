// Copies the self-hosted fonts and generates the icon module used by the storefront.
// Run once after `npm install`: npm run assets
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const nm = (...p) => path.join(root, 'node_modules', ...p);
const out = (...p) => path.join(root, 'public', ...p);

fs.mkdirSync(out('fonts'), { recursive: true });

const fonts = [
  ['@fontsource/instrument-sans/files/instrument-sans-latin-400-normal.woff2', 'instrument-sans-400.woff2'],
  ['@fontsource/instrument-sans/files/instrument-sans-latin-500-normal.woff2', 'instrument-sans-500.woff2'],
  ['@fontsource/instrument-sans/files/instrument-sans-latin-600-normal.woff2', 'instrument-sans-600.woff2'],
  ['@fontsource/instrument-serif/files/instrument-serif-latin-400-normal.woff2', 'instrument-serif-400.woff2'],
  ['@fontsource/jetbrains-mono/files/jetbrains-mono-latin-400-normal.woff2', 'jetbrains-mono-400.woff2'],
  ['@fontsource/jetbrains-mono/files/jetbrains-mono-latin-500-normal.woff2', 'jetbrains-mono-500.woff2'],
];
for (const [from, to] of fonts) fs.copyFileSync(nm(from), out('fonts', to));

// lucide, one set, drawn at 16 or 18px with a 1.5 stroke
const names = [
  'search', 'shopping-bag', 'map-pin', 'plus', 'minus', 'x', 'trash-2', 'check', 'chevron-right',
  'chevron-down', 'arrow-right', 'arrow-left', 'package', 'truck', 'database', 'radio', 'activity',
  'receipt', 'mail', 'banknote', 'smartphone', 'circle-alert', 'menu', 'sliders-horizontal', 'clock',
  'rotate-ccw', 'store', 'layers', 'timer', 'shield-check', 'refresh-cw',
];
const icons = {};
for (const n of names) {
  const svg = fs.readFileSync(nm('lucide-static', 'icons', `${n}.svg`), 'utf8');
  icons[n] = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/\s+/g, ' ').trim();
}
fs.writeFileSync(
  out('js', 'icons.js'),
  `// Generated by scripts/build-assets.js from lucide-static (ISC license).\nconst paths = ${JSON.stringify(icons, null, 2)};\n\nexport function icon(name, size = 16) {\n  return \`<svg class="icon" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${paths[name]}</svg>\`;\n}\n`,
);
console.log(`copied ${fonts.length} fonts, wrote ${names.length} icons`);
